// Language Switching System (True i18n)
// ==========================================
function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('language', lang);

  // Update Body classes and HTML attributes
  if (lang === 'en') {
    document.body.classList.remove('ta');
    document.body.classList.add('en');
    document.documentElement.lang = 'en';
  } else {
    document.body.classList.remove('en');
    document.body.classList.add('ta');
    document.documentElement.lang = 'ta';
  }

  // Update text of all i18n items in page
  const translatableElements = document.querySelectorAll('[data-i18n]');
  translatableElements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Highlight active language button in header
  const btnTa = document.getElementById('btn-lang-ta');
  const btnEn = document.getElementById('btn-lang-en');
  if (lang === 'en') {
    btnTa.classList.remove('active');
    btnEn.classList.add('active');
  } else {
    btnEn.classList.remove('active');
    btnTa.classList.add('active');
  }

  // Update Lightbox Captions if active
  const lightbox = document.getElementById('museumLightbox');
  if (lightbox && lightbox.classList.contains('active')) {
    updateLightboxCaptions();
  }
}

