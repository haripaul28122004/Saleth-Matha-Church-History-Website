// Lazy Loading & Scroll Reveals
// ==========================================
function initScrollAnimations() {
  // Intersection Observer for Lazy Loading Images
  const lazyImages = document.querySelectorAll('img[data-src]');
  const imageObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const img = entry.target;
        img.src = img.getAttribute('data-src');
        img.removeAttribute('data-src');
        imageObserver.unobserve(img);
      }
    });
  }, { rootMargin: '0px 0px 200px 0px' });

  lazyImages.forEach(image => imageObserver.observe(image));

  // Intersection Observer for Fade In / Slide Up
  const revealElements = document.querySelectorAll('.reveal-on-scroll, .timeline-item');
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('reveal-visible');
        if (entry.target.classList.contains('timeline-item')) {
          entry.target.classList.add('active');
        }
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });

  revealElements.forEach(el => revealObserver.observe(el));
}

// ==========================================
// Statistics Counters Animation
// ==========================================
function initStatsObserver() {
  const statsSection = document.getElementById('stats');
  const statNumbers = document.querySelectorAll('.stat-number');
  
  if (!statsSection) return;

  const statsObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        statNumbers.forEach(num => {
          if (num.getAttribute('data-type') === 'text') return; // Skip date string card
          
          const target = parseInt(num.getAttribute('data-target'), 10);
          let current = 0;
          const duration = 2000; // 2 seconds
          const stepTime = Math.abs(Math.floor(duration / target));
          
          const timer = setInterval(() => {
            current += 1;
            num.textContent = current;
            if (current >= target) {
              num.textContent = target;
              clearInterval(timer);
            }
          }, stepTime);
        });
        statsObserver.unobserve(statsSection);
      }
    });
  }, { threshold: 0.3 });

  statsObserver.observe(statsSection);
}

